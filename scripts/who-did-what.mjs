import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { checkCommitMessage } from "./check-commit-msg.mjs";

/**
 * `npm run who-did-what` — generate docs/WHO_DID_WHAT.md from git log.
 *
 * Groups commits by agent (from the [agent] prefix in the message),
 * newest first, one plain-English line per change. Backfills from existing
 * history; a commit whose agent cannot be known is grouped under UNKNOWN,
 * never guessed. A commit without the [agent][task-id][gates] prefix keeps
 * its message as-is and is flagged as unformatted.
 *
 * Run: `node scripts/who-did-what.mjs` (writes docs/WHO_DID_WHAT.md).
 */

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

function gitLog() {
  const args = [
    "log",
    "--format=%x1e%H%x1f%an%x1f%ad%x1f%s",
    "--name-only",
    "--no-renames",
    "--date=short",
  ];
  if (process.argv.includes("--exclude-head")) args.push("HEAD^");
  const out = execFileSync("git", args, {
    cwd: repoRoot,
    encoding: "utf-8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return out
    .split("\x1e")
    .map((rec) => rec.trim())
    .filter(Boolean)
    .flatMap((rec) => {
      const [metadata, ...files] = rec.split(/\r?\n/);
      const [hash, author, date, subject] = metadata.split("\x1f");
      const changedFiles = files
        .map((file) => file.trim())
        .filter(Boolean);
      const reportOnlyFiles = new Set([
        "docs/CAPABILITY_QUEUE.md",
        "docs/GATES.md",
        "docs/WHO_DID_WHAT.md",
      ]);
      if (
        changedFiles.length > 0 &&
        changedFiles.every((file) => reportOnlyFiles.has(file))
      ) {
        return [];
      }
      return [
        {
          hash: hash.slice(0, 7),
          author,
          date,
          subject: (subject || "").trim(),
        },
      ];
    });
}

const commits = gitLog();
const groups = new Map();
for (const c of commits) {
  const checked = checkCommitMessage(c.subject);
  const agent = checked.ok ? checked.agent : "UNKNOWN";
  if (!groups.has(agent)) groups.set(agent, []);
  groups.get(agent).push({
    ...c,
    taskId: checked.ok ? checked.taskId : "-",
    gates: checked.ok ? checked.gates : "-",
    formatted: checked.ok,
  });
}

// Order groups: known agents first (by newest commit), UNKNOWN last.
const ordered = [...groups.entries()].sort(([a, ac], [b, bc]) => {
  if (a === "UNKNOWN") return 1;
  if (b === "UNKNOWN") return -1;
  return bc[0].date.localeCompare(ac[0].date) || bc[0].hash.localeCompare(ac[0].hash);
});

const lines = [];
lines.push("# WHO_DID_WHAT.md — who did what, from git log");
lines.push("");
lines.push(
  "Generated by `npm run who-did-what` (scripts/who-did-what.mjs). Do not hand-edit: regenerate.",
);
lines.push("");
lines.push(
  "Grouped by agent, newest first, one plain-English line per change. A commit whose agent cannot be known is grouped under UNKNOWN, never guessed. A commit without the `[agent][task-id][gates]` prefix is flagged as unformatted.",
);
lines.push("");
for (const [agent, list] of ordered) {
  lines.push(`## ${agent}`);
  lines.push("");
  for (const c of list) {
    const flag = c.formatted ? "" : " (unformatted — no [agent][task-id][gates] prefix)";
    // Formatted commits already carry the prefix in the subject; strip it
    // so the line does not repeat [agent][task-id][gates] twice.
    const subject = c.formatted
      ? c.subject.replace(/^\[[^\]]+\]\[[^\]]+\]\[[^\]]+\]\s*/, "")
      : c.subject;
    lines.push(`- ${c.date} \`${c.hash}\` [${c.taskId}][${c.gates}] ${subject}${flag}`);
  }
  lines.push("");
}
lines.push(`Total: ${commits.length} commits.`);
lines.push("");

const outPath = join(repoRoot, "docs", "WHO_DID_WHAT.md");
writeFileSync(outPath, lines.join("\n"));
console.log(
  `who-did-what wrote ${outPath} — ${commits.length} commits, ${groups.size} agents (${[...groups.keys()].join(", ")})`,
);
